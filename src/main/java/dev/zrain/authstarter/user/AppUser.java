package dev.zrain.authstarter.user;

import jakarta.persistence.*;
import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "users", uniqueConstraints = @UniqueConstraint(name = "uk_users_email", columnNames = "email"))
    /* BM: Memodelkan pengguna dengan UUID, hash kata laluan, role dan masa penciptaan untuk penyimpanan JPA.
       EN: Models users with UUID, password hash, role and creation time for JPA persistence. */
public class AppUser {
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false, length = 254)
    private String email;

    @Column(name = "password_hash", nullable = false, length = 255)
    private String passwordHash;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Role role;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /* BM: Sediakan konstruktor terlindung untuk penginstansan JPA tanpa mendedahkan pembinaan entiti kosong kepada API.
       EN: Provide a protected constructor for JPA materialization without exposing empty entities to the API. */
    protected AppUser() {}

    /* BM: Sediakan konstruktor terlindung untuk penginstansan JPA tanpa mendedahkan pembinaan entiti kosong kepada API.
       EN: Provide a protected constructor for JPA materialization without exposing empty entities to the API. */
    public AppUser(String email, String passwordHash, Role role) {
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role;
        this.createdAt = Instant.now();
    }

    /* BM: Pulangkan UUID entiti yang dihasilkan JPA.
       EN: Return the entity UUID generated by JPA. */
    public UUID getId() { return id; }
    /* BM: Pulangkan emel ternormal tanpa mengubah state.
       EN: Return the normalized email without changing state. */
    public String getEmail() { return email; }
    /* BM: Dedahkan hash hanya kepada logik pengesahan backend, bukan DTO respons.
       EN: Expose the hash only to backend verification logic, never to response DTOs. */
    public String getPasswordHash() { return passwordHash; }
    /* BM: Pulangkan role yang digunakan untuk tuntutan akses JWT.
       EN: Return the role used in JWT access claims. */
    public Role getRole() { return role; }
    /* BM: Pulangkan cap masa asal pembinaan entiti untuk audit pengguna.
       EN: Return the original entity creation timestamp for user audit. */
    public Instant getCreatedAt() { return createdAt; }
}
